def build_quiz_md():
    lines = ["# 《人工智能导论：模型与算法》测验", "",
             "每章 4 题，先自己做，再看答案。题目与各章自测题同源，答案已逐条核对。", ""]
    ch_title = {c[0]: c[1] for c in CHAPTERS}
    for ch in [c[0] for c in CHAPTERS]:
        lines.append(f"## {ch_title[ch]}")
        items = [q for q in QUIZZES if q[0] == ch]
        for i, (_, typ, stem, opts, ans, exp) in enumerate(items, 1):
            kind = {"single": "单选", "multi": "多选", "blank": "填空"}[typ]
            lines.append(f"### Q{i}（{kind}）{stem}")
            if opts:
                letters = "ABCD"
                lines.append("")
                lines.append("  ".join(f"{letters[j]}. {o}" for j, o in enumerate(opts)))
            if typ == "single":
                answer = "ABCD"[ans]
            elif typ == "multi":
                answer = "、".join("ABCD"[j] for j in ans)
            else:
                answer = ans
            lines.append("")
            lines.append(f"**答案**：{answer}")
            lines.append(f"**解析**：{exp}")
            lines.append("")
    # 综合
    lines.append("## 综合测验（多章联考）")
    lines.append("### Q1（简答）用一个具体任务说明五种范式各自的成本与收益。")
    lines.append("")
    lines.append("**评分要点**：任务具体；五种做法都能说清信息源；能指出可解释性与数据需求的差异。")
    lines.append("")
    lines.append("### Q2（简答）给定一组\"做了手术恢复更好\"的观察数据，如何判断能否得出因果结论？")
    lines.append("")
    lines.append("**评分要点**：识别混杂因子；区分观察与干预；说明分层或加权的作用；指出反事实需要模型。")
    lines.append("")
    lines.append("## 最终检验")
    lines.append("选一个你熟悉的场景（如校园二手交易定价、图书馆座位分配），写一份 800 字方案：")
    lines.append("")
    lines.append("1. 明确任务属于五种范式中的哪一种，理由是什么。")
    lines.append("2. 给出数据需求、评价指标、可能的失败模式。")
